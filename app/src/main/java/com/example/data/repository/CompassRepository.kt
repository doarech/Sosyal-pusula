    // Thread-safe question stockpile pre-generated by AI in background
    private val questionStockpile = Collections.synchronizedList(mutableListOf<List<DynamicQuestion>>())
    private var isPrefetching = false

    fun getTasksForCheckIn(checkInId: Long): Flow<List<DailyTaskEntity>> {
        return dao.getTasksForCheckIn(checkInId)
    }

    /**
     * Pre-fetches and stockpiles AI questions in the background while the user interacts with the app.
     */
    suspend fun prefetchQuestionsInBackground() = withContext(Dispatchers.IO) {
        if (isPrefetching || questionStockpile.size >= 3) return@withContext
        isPrefetching = true
        try {
            val freshQuestions = aiService.generateDynamicQuestions()
            if (freshQuestions.isNotEmpty()) {
                questionStockpile.add(freshQuestions)
                Log.d("CompassRepository", "Stockpiled fresh AI questions. Total ready in queue: ${questionStockpile.size}")
            }
        } catch (e: Exception) {
            Log.w("CompassRepository", "Background AI prefetch failed", e)
        } finally {
            isPrefetching = false
        }
    }

    /**
     * Returns dynamic AI questions. Uses stocked background questions when ready
     * and triggers automatic background replenishment.
     */
    suspend fun fetchDynamicQuestions(): List<DynamicQuestion> {
        // If we have stocked questions, serve immediately with zero wait!
        if (questionStockpile.isNotEmpty()) {
            val stocked = questionStockpile.removeAt(0)
            CoroutineScope(Dispatchers.IO).launch {
                prefetchQuestionsInBackground()
            }
            return stocked
        }

        // Otherwise generate on-demand and trigger background replenishment
        val questions = aiService.generateDynamicQuestions()
        CoroutineScope(Dispatchers.IO).launch {
            prefetchQuestionsInBackground()
        }
        return questions
    }

