class CompassRepository(
    private val dao: CompassDao,
    private val aiService: AiService
) {

    val allCheckIns: Flow<List<CheckInEntity>> = dao.getAllCheckIns()
    val latestCheckIn: Flow<CheckInEntity?> = dao.getLatestCheckIn()
    val allTasks: Flow<List<DailyTaskEntity>> = dao.getAllTasks()

    // Thread-safe question stockpile pre-generated by AI in background
    private val questionStockpile = Collections.synchronizedList(mutableListOf<List<DynamicQuestion>>())
    private var isPrefetching = false

    fun getTasksForCheckIn(checkInId: Long): Flow<List<DailyTaskEntity>> {
        return dao.getTasksForCheckIn(checkInId)
    }

    /**
     * Pre-fetches and stockpiles AI questions in the background while the user interacts with the app.
     */
    suspend fun prefetchQuestionsInBackground() = withContext(Dispatchers.IO) {
        if (isPrefetching || questionStockpile.size >= 3) return@withContext
        isPrefetching = true
        try {
            val freshQuestions = aiService.generateDynamicQuestions()
            if (freshQuestions.isNotEmpty()) {
                questionStockpile.add(freshQuestions)
                Log.d("CompassRepository", "Stockpiled fresh AI questions. Total ready in queue: ${questionStockpile.size}")
            }
        } catch (e: Exception) {
            Log.w("CompassRepository", "Background AI prefetch failed", e)
        } finally {
            isPrefetching = false
        }
    }

    /**
     * Returns dynamic AI questions. Uses stocked background questions when ready
     * and triggers automatic background replenishment.
     */
    suspend fun fetchDynamicQuestions(): List<DynamicQuestion> {
        // If we have stocked questions, serve immediately with zero wait!
        if (questionStockpile.isNotEmpty()) {
            val stocked = questionStockpile.removeAt(0)
            CoroutineScope(Dispatchers.IO).launch {
                prefetchQuestionsInBackground()
            }
            return stocked
        }

        // Otherwise generate on-demand and trigger background replenishment
        val questions = aiService.generateDynamicQuestions()
        CoroutineScope(Dispatchers.IO).launch {
            prefetchQuestionsInBackground()
        }
        return questions
    }

    suspend fun saveCheckInWithAi(
        answers: List<Pair<String, String>>,
        screenHours: Float,
        userNotes: String
    ): CheckInEntity {
        val currentWeek = getCurrentWeekString()
        val analysis = aiService.evaluateLonelinessAndGeneratePlan(answers, screenHours, userNotes)

        val checkIn = CheckInEntity(
            weekString = currentWeek,
            timestamp = System.currentTimeMillis(),
            score = analysis.score,
            screenHours = screenHours,
            aiSummary = analysis.summary,
            levelLabel = analysis.levelLabel,
            motivationQuote = analysis.motivationQuote,
            motivationAuthor = analysis.motivationAuthor
        )

        val checkInId = dao.insertCheckIn(checkIn)

        val todayDate = SimpleDateFormat("dd MMM", Locale("tr")).format(Date())
        val taskEntities = analysis.tasks.map {
            DailyTaskEntity(
                checkInId = checkInId,
                title = it.title,
                category = it.category,
                isCompleted = false,
                dateString = todayDate
            )
        }
        dao.insertTasks(taskEntities)

        // Refill question stockpile in background after completing a check-in
        CoroutineScope(Dispatchers.IO).launch {
            prefetchQuestionsInBackground()
        }

        return checkIn.copy(id = checkInId)
    }

    suspend fun toggleTaskCompletion(taskId: Long, isCompleted: Boolean) {
        dao.updateTaskCompletion(taskId, isCompleted)
    }

    suspend fun saveTaskReflection(taskId: Long, reflection: String) {
        val completed = reflection.isNotBlank()
        dao.updateTaskReflection(taskId, reflection, isCompleted = completed)
    }

    suspend fun deleteCheckIn(id: Long) {
        dao.deleteTasksForCheckIn(id)
        dao.deleteCheckIn(id)
    }

    suspend fun seedInitialDataIfEmpty() {
        if (dao.getCheckInCount() == 0) {
            val mockData = listOf(
                0 to Triple(22, 3.2f, "Bir insanı sevmekle başlar her şey." to "Sait Faik Abasıyanık"),
                1 to Triple(42, 4.5f, "İnsan, insanın sığınağıdır." to "Cemil Meriç"),
                2 to Triple(68, 6.8f, "Karanlığa küfredeceğine bir mum yak." to "Konfüçyüs"),
                3 to Triple(28, 3.6f, "Yalnız kalma cesaretini gösteremeyen insan, başkalarıyla da sahici bir bağ kuramaz." to "Erich Fromm")
            )

            for ((weeksAgo, values) in mockData) {
                val (score, screen, quotePair) = values
                val weekCal = Calendar.getInstance().apply {
                    add(Calendar.WEEK_OF_YEAR, -weeksAgo)
                }
                val year = weekCal.get(Calendar.YEAR)
                val weekNo = weekCal.get(Calendar.WEEK_OF_YEAR)
                val weekStr = "$year-W$weekNo"

                val checkIn = CheckInEntity(
                    weekString = weekStr,
                    timestamp = weekCal.timeInMillis,
                    score = score,
                    screenHours = screen,
                    aiSummary = "Haftalık rutininde ekran süresini düşürmen sosyal enerjine olumlu yansıdı.",
                    levelLabel = when {
                        score >= 76 -> "Şiddetli Yalnızlık"
                        score >= 51 -> "Yüksek Yalnızlık"
                        score >= 26 -> "Orta Seviye"
                        else -> "Düşük Yalnızlık (İyi)"
                    },
                    motivationQuote = quotePair.first,
                    motivationAuthor = quotePair.second
                )
                val checkInId = dao.insertCheckIn(checkIn)

                val tasks = listOf(
                    DailyTaskEntity(
                        checkInId = checkInId,
                        title = "Bugün bir arkadaşına sesli mesaj gönder.",
                        category = "Sosyal",
                        isCompleted = true,
                        dateString = "Önceki Hafta"
                    ),
                    DailyTaskEntity(
                        checkInId = checkInId,
                        title = "Yemek yerken ekranı kapat.",
                        category = "Dijital Detoks",
                        isCompleted = true,
                        dateString = "Önceki Hafta"
                    )
                )
                dao.insertTasks(tasks)
            }
        }
    }

    fun getCurrentWeekString(): String {
        val cal = Calendar.getInstance()
        val year = cal.get(Calendar.YEAR)
        val weekNo = cal.get(Calendar.WEEK_OF_YEAR)
        return "$year-W$weekNo"
    }

    fun formatWeekLabel(weekString: String): String {
        return try {
            val parts = weekString.split("-W")
            if (parts.size == 2) {
                "${parts[1]}. Hafta"
            } else {
                weekString
            }
        } catch (e: Exception) {
            weekString
        }
    }

    fun calculateCorrelation(checkIns: List<CheckInEntity>): Float {
        if (checkIns.size < 2) return 0f

        val n = checkIns.size.toFloat()
        val x = checkIns.map { it.screenHours }
        val y = checkIns.map { it.score.toFloat() }

        val sumX = x.sum()
        val sumY = y.sum()

        val sumXSquare = x.sumOf { (it * it).toDouble() }.toFloat()
        val sumYSquare = y.sumOf { (it * it).toDouble() }.toFloat()

        var sumXY = 0f
        for (i in checkIns.indices) {
            sumXY += x[i] * y[i]
        }

        val numerator = (n * sumXY) - (sumX * sumY)
        val denominatorPart1 = (n * sumXSquare) - (sumX * sumX)
        val denominatorPart2 = (n * sumYSquare) - (sumY * sumY)

        val denominator = sqrt(denominatorPart1 * denominatorPart2)

        return if (denominator == 0f) 0f else (numerator / denominator).coerceIn(-1f, 1f)
    }
}
